package task

import (
	"encoding/json"
	"fmt"
	"sync"
	"time"
)

type TaskStatus string

const (
	StatusPending    TaskStatus = "pending"
	StatusInProgress TaskStatus = "in_progress"
	StatusCompleted  TaskStatus = "completed"
	StatusFailed     TaskStatus = "failed"
	StatusCancelled  TaskStatus = "cancelled"
)

// Task represents a structured atomic unit of work in the multi-agent system
type Task struct {
	TaskID             string     `json:"task_id"`
	AssignedAgent      string     `json:"assigned_agent"` // "developer", "researcher", "reviewer"
	Objective          string     `json:"objective"`
	Dependencies       []string   `json:"dependencies,omitempty"`
	AcceptanceCriteria []string   `json:"acceptance_criteria"`
	Status             TaskStatus `json:"status"`
	Result             string     `json:"result,omitempty"`
	Error              string     `json:"error,omitempty"`
	RetryCount         int        `json:"retry_count"`
	MaxRetries         int        `json:"max_retries"`
	CreatedAt          time.Time  `json:"created_at"`
	UpdatedAt          time.Time  `json:"updated_at"`
}

// Plan is a structured set of tasks generated by the Planner Agent
type Plan struct {
	Objective string  `json:"objective"`
	Tasks     []*Task `json:"tasks"`
}

// Queue manages tasks with thread-safety and dependency resolution
type Queue struct {
	mu    sync.RWMutex
	tasks map[string]*Task
	order []string
}

func NewQueue() *Queue {
	return &Queue{
		tasks: make(map[string]*Task),
	}
}

func (q *Queue) Add(t *Task) error {
	q.mu.Lock()
	defer q.mu.Unlock()

	if t.TaskID == "" {
		return fmt.Errorf("task_id is required")
	}
	if t.Status == "" {
		t.Status = StatusPending
	}
	if t.MaxRetries == 0 {
		t.MaxRetries = 2
	}
	t.CreatedAt = time.Now()
	t.UpdatedAt = time.Now()

	q.tasks[t.TaskID] = t
	q.order = append(q.order, t.TaskID)
	return nil
}

func (q *Queue) Get(taskID string) (*Task, bool) {
	q.mu.RLock()
	defer q.mu.RUnlock()
	t, ok := q.tasks[taskID]
	return t, ok
}

func (q *Queue) NextReady() *Task {
	q.mu.Lock()
	defer q.mu.Unlock()

	for _, id := range q.order {
		t := q.tasks[id]
		if t.Status != StatusPending {
			continue
		}

		// Check if all dependencies are satisfied
		depsSatisfied := true
		for _, depID := range t.Dependencies {
			dep, exists := q.tasks[depID]
			if !exists || dep.Status != StatusCompleted {
				depsSatisfied = false
				break
			}
		}

		if depsSatisfied {
			t.Status = StatusInProgress
			t.UpdatedAt = time.Now()
			return t
		}
	}
	return nil
}

func (q *Queue) UpdateStatus(taskID string, status TaskStatus, result string, errStr string) {
	q.mu.Lock()
	defer q.mu.Unlock()

	if t, ok := q.tasks[taskID]; ok {
		t.Status = status
		t.Result = result
		t.Error = errStr
		t.UpdatedAt = time.Now()
	}
}

func (q *Queue) AllCompleted() bool {
	q.mu.RLock()
	defer q.mu.RUnlock()

	if len(q.tasks) == 0 {
		return true
	}
	for _, t := range q.tasks {
		if t.Status != StatusCompleted {
			return false
		}
	}
	return true
}

func (q *Queue) HasPendingOrRunning() bool {
	q.mu.RLock()
	defer q.mu.RUnlock()

	for _, t := range q.tasks {
		if t.Status == StatusPending || t.Status == StatusInProgress {
			return true
		}
	}
	return false
}

func (q *Queue) List() []*Task {
	q.mu.RLock()
	defer q.mu.RUnlock()

	var list []*Task
	for _, id := range q.order {
		list = append(list, q.tasks[id])
	}
	return list
}

func (q *Queue) ToJSON() string {
	q.mu.RLock()
	defer q.mu.RUnlock()

	data, _ := json.MarshalIndent(q.List(), "", "  ")
	return string(data)
}
